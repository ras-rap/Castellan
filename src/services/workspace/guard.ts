import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { paths } from '@services/config.ts';
import { log } from '@utils/logger.ts';

const logger = log('workspace/guard');

/**
 * Where opencode looks for plugins when `XDG_CONFIG_HOME` points at our data directory: a bot-owned config
 * dir, so the guard cannot collide with the owner's own opencode setup and is regenerated from code.
 */
export const configHome = (): string => resolve(paths.data, 'opencode/config');
export const guardPath = (): string => resolve(configHome(), 'opencode/plugin/castellan-guard.ts');

/**
 * The host-shell guard, as an opencode plugin.
 *
 * `opencode.json` cannot remove opencode's own `bash` tool: `tools: { bash: false }` and
 * `permission: { bash: "deny" }` are both ignored for it in 1.19.5 (measured — the tool ran either way), so a
 * "sandboxed by default" server was one tool call from executing on the host next to the bot's `.env`. The
 * plugin hook `tool.execute.before` does run before every tool, and throwing there aborts the call, so the
 * builtin shell is refused by construction. The same hook confines the host file tools to the workspace, which
 * is the sandbox boundary.
 *
 * It is inert without `BRIDGE_TOKEN`, and inert in **host** mode: a guild whose owner set `shell.mode: "host"`
 * has already handed this server the bot user, so opencode's raw `bash` is theirs to use and the guard must not
 * pretend otherwise. Only the sandboxed mode needs a wall.
 */
const source = `// Generated by Castellan at boot. Do not edit: overwritten from src/services/workspace/guard.ts.
import { resolve, sep } from "node:path";

const ROOT = process.cwd();
/** opencode's own shell: it runs in this process, on the host, not in the guild's container. */
const HOST_SHELL = new Set(["bash"]);
/** Host file tools: fine inside the workspace, never outside it. */
const FILE_TOOLS = new Set(["read", "write", "edit", "apply_patch", "patch", "glob", "grep", "list"]);

const inside = (value: unknown): boolean => {
  if (typeof value !== "string" || value.length === 0) return true;
  const resolved = resolve(ROOT, value);
  return resolved === ROOT || resolved.startsWith(ROOT + sep);
};

export const CastellanGuard = async () => {
  // Only sessions this bot started carry the bridge token; a hand-run opencode is left alone.
  if (!process.env.BRIDGE_TOKEN) return {};
  // Host mode: the guild owner decided this server may have the machine, so the raw shell stays available.
  if (process.env.CASTELLAN_SHELL_MODE === "host") return {};
  return {
    "tool.execute.before": async (input: { tool?: string }, output: { args?: Record<string, unknown> }) => {
      const tool = input?.tool ?? "";
      if (HOST_SHELL.has(tool))
        throw new Error(
          "no host shell in this workspace: use the discord_shell tool, which runs through this server's sandbox",
        );
      if (!FILE_TOOLS.has(tool)) return;
      const args = output?.args ?? {};
      for (const key of ["filePath", "path", "file", "pattern", "directory"]) {
        if (!inside(args[key])) throw new Error("refused: " + key + " points outside the workspace");
      }
    },
  };
};
`;

/** Idempotent: the file is compared before writing, so a restart never touches its mtime. */
export function ensureGuardPlugin(): string {
  const target = guardPath();
  mkdirSync(resolve(target, '..'), { 'recursive': true });
  try {
    if (readFileSync(target, 'utf8') === source) return target;
  } catch {
    // not written yet
  }
  writeFileSync(target, source, 'utf8');
  logger.info('host-shell guard written', { target });
  return target;
}
